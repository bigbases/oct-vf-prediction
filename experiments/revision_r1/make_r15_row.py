"""Calibration table (Table 9, tab:calibration): the 'Centred image (IR-v2)' row, generated
straight from the frozen R1-5 addendum (centred_irv2.json, block 'calibration', stratum 'all').

Columns as in the table: out-of-fold mean bias [CI] and slope [CI], then the same held-out.
With --manuscript, the six rows already in the table are rendered from the frozen
calibration_multiplicity.json by the same function and each must appear verbatim in that
file, so the new row follows the rule the existing rows were written with.

After writing, the row is parsed back and every printed number is compared with the JSON.

    python experiments/revision_r1/make_r15_row.py --out <row.tex> [--manuscript <results.tex>]
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FROZEN = ROOT / 'paper/results_frozen'
NEW = ('centred_irv2.json', 'Centred IR-v2', 'Centred image (IR-v2)')
# calibration_multiplicity.json branch -> label in the submitted-revision table, in table order
EXISTING = [('Summary', 'Summary'), ('IR-v2', 'Image (IR-v2)'), ('Ensemble', 'Image ensemble'),
            ('Centred ensemble', 'Centred ensemble'), ('Fusion', 'Fusion (IR-v2)'),
            ('Ensemble fusion', 'Ensemble fusion')]
SPLITS = ('OOF', 'TEST')


def bias(v, ci):
    return f'${v:+.2f}$ [${ci[0]:+.2f}$, ${ci[1]:+.2f}$]'


def slope(v, ci):
    return f'{v:.3f} [{ci[0]:.3f}, {ci[1]:.3f}]'


def row(label, cal, branch):
    cells = []
    for s in SPLITS:
        r = cal[s][branch]['all']
        cells += [bias(r['mean_bias'], r['mean_bias_ci']), slope(r['slope'], r['slope_ci'])]
    return f'{label} & ' + ' & '.join(cells) + ' \\\\'


def load(name):
    raw = (FROZEN / name).read_bytes()
    return json.loads(raw), hashlib.sha256(raw).hexdigest()


def render():
    d, h = load(NEW[0])
    lines = [f'% Generated by experiments/revision_r1/make_r15_row.py from paper/results_frozen/'
             f'{NEW[0]} (sha256 {h[:16]}).',
             '% Do not edit the numbers by hand.',
             row(NEW[2], d['calibration'], NEW[1])]
    return '\n'.join(lines) + '\n', d


# -- read-back check, independent of row() --------------------------------------------------
B = r'\$([+-]\d+\.\d{2})\$ \[\$([+-]\d+\.\d{2})\$, \$([+-]\d+\.\d{2})\$\]'
S = r'(-?\d+\.\d{3}) \[(-?\d+\.\d{3}), (-?\d+\.\d{3})\]'
ROW = re.compile('^' + re.escape(NEW[2]) + ' & ' + ' & '.join([B, S] * 2) + r' \\\\$')


def check(tex, d):
    hits = [ROW.match(line) for line in tex.splitlines()]
    hits = [m for m in hits if m]
    assert len(hits) == 1, len(hits)
    toks = [float(t) for t in hits[0].groups()]
    want = []
    for s in SPLITS:
        r = d['calibration'][s][NEW[1]]['all']
        want += [(r['mean_bias'], 0.005), (r['mean_bias_ci'][0], 0.005), (r['mean_bias_ci'][1], 0.005),
                 (r['slope'], 0.0005), (r['slope_ci'][0], 0.0005), (r['slope_ci'][1], 0.0005)]
    for got, (v, tol) in zip(toks, want):
        assert abs(got - v) <= tol + 1e-12, (got, v)
    return len(toks)


def check_existing(manuscript):
    """The six rows of the table, rendered by row(), must be in the manuscript verbatim."""
    cm, _ = load('calibration_multiplicity.json')
    text = manuscript.read_text(encoding='utf-8')
    for branch, label in EXISTING:
        r = row(label, cm['calibration'], branch)
        assert r in text, f'not in {manuscript.name}: {r}'
    return len(EXISTING)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--out', required=True, type=Path)
    ap.add_argument('--manuscript', type=Path)
    args = ap.parse_args()
    tex, d = render()
    args.out.write_text(tex, encoding='utf-8')
    n = check(args.out.read_text(encoding='utf-8'), d)
    msg = f'wrote {args.out}: {n} numbers, each matches the frozen R1-5 addendum'
    if args.manuscript:
        msg += f'; the {check_existing(args.manuscript)} existing rows render verbatim as in {args.manuscript.name}'
    print(msg)


if __name__ == '__main__':
    main()
